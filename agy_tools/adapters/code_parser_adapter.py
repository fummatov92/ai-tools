import os
import sys
from typing import List, Dict, Any, Optional
from agy_tools.adapters.base_adapter import BaseAdapter

# Ensure code_parser package is on path
PACKAGE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "modules", "code_parser"))
if PACKAGE_DIR not in sys.path:
    sys.path.insert(0, PACKAGE_DIR)

from detector import detect_framework
from finder import find_files
from parsers import get_parser_module

class CodeParserAdapter(BaseAdapter):
    """
    Universal AST adapter bridging code_parser into doc_tool.
    Supports Express, NestJS, FastAPI, Flask, Django, Gin, Fiber, and Laravel.
    """
    def __init__(self, project_path: str):
        super().__init__(project_path)
        self.meta = detect_framework(self.project_path)
        self.framework = self.meta.get("type", "Unknown")
        self.language = self.meta.get("language", "Unknown")

    def detect(self) -> bool:
        # Detects Python apps (FastAPI, Flask, Django) or anything detected by code_parser
        if self.language in ["python", "Python"]:
            return True
        return self.framework not in ["Unknown", "Generic App"]

    def scan(self) -> List[Dict[str, Any]]:
        """Extracts and normalizes endpoints across all supported languages."""
        files = find_files(self.project_path)
        endpoints: List[Dict[str, Any]] = []

        if self.language in ["javascript", "typescript", "JavaScript", "TypeScript"]:
            js_mod = get_parser_module(".ts")
            raw_eps = js_mod.scan_project_endpoints(self.project_path, files)
        elif self.language in ["python", "Python"]:
            py_mod = get_parser_module(".py")
            raw_eps = py_mod.scan_project_endpoints(self.project_path, files)
        elif self.language in ["go", "Go"]:
            go_mod = get_parser_module(".go")
            raw_eps = go_mod.scan_project_endpoints(self.project_path, files)
        elif self.language in ["php", "PHP"]:
            php_mod = get_parser_module(".php")
            raw_eps = php_mod.scan_project_endpoints(self.project_path, files)
        else:
            raw_eps = []

        for ep in raw_eps:
            path = ep.get("path", "/")
            method = ep.get("method", "GET").upper()
            file_path = ep.get("file", "")
            line = ep.get("line", 1)
            handler = ep.get("handler", "handler")

            segments = [s for s in path.strip("/").split("/") if s and not s.startswith(":") and not s.startswith("{")]
            module_name = segments[0].capitalize() if segments else "Core"
            if module_name.lower() in ["api", "v1", "v2"]:
                module_name = segments[1].capitalize() if len(segments) > 1 else "General"

            endpoints.append({
                "method": method,
                "path": path,
                "file": file_path,
                "line": line,
                "handler": handler,
                "module": module_name,
                "controller_class": f"{module_name}Controller",
                "summary": f"{method} {path} handler",
                "description": f"Autogenerated contract from {os.path.basename(file_path)}:{line}",
                "auth_required": any(w in path.lower() or w in handler.lower() for w in ["auth", "login", "admin", "secure", "token"]),
                "rate_limit": "60 req/min"
            })

        return endpoints
